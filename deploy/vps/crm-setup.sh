#!/usr/bin/env bash
# =====================================================================================================
# Smart Sales CRM — install / update on a single Ubuntu server (host Caddy, host PostgreSQL 16).
# Usage (as root):  CRM_DOMAIN=crm.example.com bash crm-setup.sh <release.tgz> [Caddyfile]
# On later runs CRM_DOMAIN may be omitted: it is read from APP_URL in /etc/crm/crm.env.
#
#   code      /opt/crm                (previous release kept in /opt/crm.prev for rollback)
#   service   systemd "crm", user "crm", 127.0.0.1:3002
#   config    /etc/crm/crm.env        (root:crm 640; secrets generated here with openssl, only on first run)
#   data      /var/lib/crm/{uploads,media}
#   database  PostgreSQL db "crm", roles crm_owner (migrations) + crm_app (NOBYPASSRLS)
#   backups   /var/backups/crm, daily 03:15, kept 14 days
# Idempotent: re-running updates the code and keeps secrets, database and files. Never touches other
# databases or sites. A new Caddyfile is installed only if `caddy validate` passes.
# =====================================================================================================
set -euo pipefail

RELEASE="${1:?usage: crm-setup.sh <release.tgz> [Caddyfile]}"
CADDY_NEW="${2:-}"
DOMAIN="${CRM_DOMAIN:-}"
[ -z "$DOMAIN" ] && [ -f /etc/crm/crm.env ] && DOMAIN="$(sed -n 's#^APP_URL=https\{0,1\}://\([^/]*\).*#\1#p' /etc/crm/crm.env | head -1)"
PORT="${CRM_PORT:-3002}"
APP=/opt/crm; ETC=/etc/crm; ENVF=$ETC/crm.env; DATA=/var/lib/crm; BK=/var/backups/crm
DB=crm; OWNER=crm_owner; APPROLE=crm_app
PGPORT="${CRM_PG_PORT:-5432}"
PSQL_ARGS=(-p "$PGPORT"); [ -n "${CRM_PG_SOCKET:-}" ] && PSQL_ARGS+=(-h "$CRM_PG_SOCKET")
NO_SYSTEMD="${CRM_NO_SYSTEMD:-0}"            # testing hook (containers without systemd)

say()  { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m  ✓ %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m  ✗ %s\033[0m\n' "$*" >&2; exit 1; }
pg()   { runuser -u postgres -- psql "${PSQL_ARGS[@]}" -v ON_ERROR_STOP=1 -qAt "$@"; }

[ "$(id -u)" = 0 ] || die "run as root"
[ -n "$DOMAIN" ] || die "set CRM_DOMAIN (e.g. CRM_DOMAIN=crm.example.com) for the first install"
[ -f "$RELEASE" ] || die "release archive not found: $RELEASE"

say "1/8 Checking the server"
NODE="$(command -v node || true)"; [ -n "$NODE" ] || die "Node.js is not installed"
NODE_V="$($NODE -v)"; node -e 'const [a,b]=process.versions.node.split(".").map(Number);process.exit(a>22||(a===22&&b>=12)?0:1)' || die "Node.js >= 22.12 required (found $NODE_V)"
command -v npm >/dev/null || die "npm is missing"
pg -c 'select 1' >/dev/null || die "PostgreSQL is not reachable as the postgres user"
ok "Node $NODE_V, PostgreSQL $(pg -c 'show server_version' | cut -d' ' -f1)"

say "2/8 System user and directories"
id crm >/dev/null 2>&1 || useradd --system --home-dir "$DATA" --shell /usr/sbin/nologin crm
install -d -o crm -g crm -m 750 "$DATA" "$DATA/uploads" "$DATA/media" "$DATA/.npm"
install -d -o root -g crm -m 750 "$ETC"
install -d -o root -g root -m 700 "$BK"
ok "user crm, $DATA, $ETC, $BK"

say "3/8 Database and secrets"
if [ ! -f "$ENVF" ]; then
  OWNER_PW="$(openssl rand -hex 24)"; APP_PW="$(openssl rand -hex 24)"
  pg <<SQL
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '$OWNER') THEN
    CREATE ROLE $OWNER LOGIN PASSWORD '$OWNER_PW' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  ELSE ALTER ROLE $OWNER WITH LOGIN PASSWORD '$OWNER_PW'; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '$APPROLE') THEN
    CREATE ROLE $APPROLE LOGIN PASSWORD '$APP_PW' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
  ELSE ALTER ROLE $APPROLE WITH LOGIN PASSWORD '$APP_PW' NOSUPERUSER NOBYPASSRLS; END IF;
END \$\$;
SQL
  pg -c "SELECT 1 FROM pg_database WHERE datname = '$DB'" | grep -q 1 || pg -c "CREATE DATABASE $DB OWNER $OWNER"
  pg -c "REVOKE ALL ON DATABASE $DB FROM PUBLIC" -c "GRANT CONNECT ON DATABASE $DB TO $APPROLE"
  umask 027
  cat > "$ENVF" <<ENV
# Smart Sales CRM — generated by crm-setup.sh on $(date -u +%F). Keep a copy in a password manager.
NODE_ENV=production
HOST=127.0.0.1
PORT=$PORT
APP_URL=https://$DOMAIN
# Cloudflare → Caddy → app: Caddy puts the visitor IP (CF-Connecting-IP) in X-Forwarded-For.
TRUST_PROXY=1
DATABASE_MIGRATION_URL=postgres://$OWNER:$OWNER_PW@127.0.0.1:$PGPORT/$DB
APP_DB_ROLE=$APPROLE
APP_DB_PASSWORD=$APP_PW
APP_ENCRYPTION_KEYS=k1:$(openssl rand -base64 32)
APP_ENCRYPTION_PRIMARY_KEY_ID=k1
WEBHOOK_SECRET_KEY=$(openssl rand -base64 32)
UPLOADS_DIR=$DATA/uploads
MEDIA_DRIVER=local
MEDIA_DIR=$DATA/media
CHANNEL_PROVIDERS=telegram
# Optional email for invitations / password resets:
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASSWORD=
MAIL_FROM=
ENV
  chown root:crm "$ENVF"; chmod 640 "$ENVF"
  ok "database $DB, roles $OWNER / $APPROLE, secrets in $ENVF (640)"
else
  chown root:crm "$ENVF"; chmod 640 "$ENVF"
  ok "existing $ENVF kept"
fi

say "4/8 Building the new release (on this server)"
rm -rf "$APP.new"; install -d -o crm -g crm "$APP.new"
tar -xzf "$RELEASE" -C "$APP.new" --no-same-owner
rm -f "$APP.new/.env"                       # never ship a laptop .env
chown -R crm:crm "$APP.new"
runuser -u crm -- env HOME="$DATA" npm_config_cache="$DATA/.npm" bash -c "cd '$APP.new' && npm ci --no-audit --no-fund --loglevel=error && npm run build --silent && npm prune --omit=dev --no-audit --no-fund --loglevel=error"
ok "dependencies installed, frontend built"

say "5/8 Migrations"
# Verified backup before touching the schema (only when the database already exists).
if runuser -u postgres -- psql "${PSQL_ARGS[@]}" -tAc "SELECT 1 FROM pg_database WHERE datname='$DB'" | grep -q 1; then
  install -d -m 700 "$BK"
  PRE="$BK/pre-deploy-$(date +%F-%H%M%S).dump"
  runuser -u postgres -- pg_dump "${PSQL_ARGS[@]}" -d "$DB" --format=custom --exclude-schema=pgboss > "$PRE" || die "pre-deploy backup failed — nothing was changed"
  chmod 600 "$PRE"
  pg_restore --list "$PRE" > /dev/null || die "pre-deploy backup is unreadable — nothing was changed"
  [ -s "$PRE" ] || die "pre-deploy backup is empty — nothing was changed"
  ok "verified backup: $PRE"
  find "$BK" -name 'pre-deploy-*.dump' -mtime +30 -delete
fi
runuser -u crm -- bash -c "set -a; . '$ENVF'; set +a; cd '$APP.new' && node scripts/prepare-database.js"

say "6/8 Service"
UNIT=/etc/systemd/system/crm.service
cat > "$UNIT.tmp" <<UNIT
[Unit]
Description=Smart Sales CRM ($DOMAIN)
After=network-online.target postgresql.service
Wants=network-online.target

[Service]
Type=simple
User=crm
Group=crm
WorkingDirectory=$APP
EnvironmentFile=$ENVF
ExecStart=$NODE server/index.js
Restart=on-failure
RestartSec=5
KillSignal=SIGTERM
TimeoutStopSec=40
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=$DATA

[Install]
WantedBy=multi-user.target
UNIT
mv "$UNIT.tmp" "$UNIT"
start_app() {
  if [ "$NO_SYSTEMD" = 1 ]; then
    pkill -u crm -f "node server/index.js" 2>/dev/null || true; sleep 1
    runuser -u crm -- bash -c "set -a; . '$ENVF'; set +a; cd '$APP' && setsid nohup $NODE server/index.js >> '$DATA/test-run.log' 2>&1 < /dev/null &"
  else
    systemctl daemon-reload; systemctl enable crm >/dev/null 2>&1; systemctl restart crm
  fi
}
stop_app() { if [ "$NO_SYSTEMD" = 1 ]; then pkill -u crm -f "node server/index.js" 2>/dev/null || true; else systemctl stop crm 2>/dev/null || true; fi; }
healthy() { for _ in $(seq 1 30); do curl -fsS --max-time 3 "http://127.0.0.1:$PORT/api/ready" >/dev/null 2>&1 && return 0; sleep 2; done; return 1; }

stop_app
rm -rf "$APP.prev"; [ -d "$APP" ] && mv "$APP" "$APP.prev"
mv "$APP.new" "$APP"
start_app
if healthy; then
  ok "crm running on 127.0.0.1:$PORT ($(curl -fsS http://127.0.0.1:$PORT/api/ready))"
else
  [ "$NO_SYSTEMD" = 1 ] || journalctl -u crm -n 40 --no-pager || true
  if [ -d "$APP.prev" ]; then
    echo "New release is not healthy — rolling back to the previous one."
    stop_app; rm -rf "$APP.failed"; mv "$APP" "$APP.failed"; mv "$APP.prev" "$APP"; start_app
    healthy && die "rolled back to the previous release (failed one kept in $APP.failed)"
  fi
  die "the application did not become ready (see the log above)"
fi

say "7/8 Caddy"
# Only Cloudflare may talk to this site: direct hits on the server IP (which could fake the visitor IP
# header and dodge rate limits) get 403. The list is refreshed from Cloudflare on every deploy, with a
# built-in fallback. Verified after reload; if the site is not reachable through Cloudflare the
# restriction is switched off automatically so the site never goes down because of it.
CFI=/etc/caddy/crm-cloudflare-only.caddy
CF_BUILTIN="173.245.48.0/20 103.21.244.0/22 103.22.200.0/22 103.31.4.0/22 141.101.64.0/18 108.162.192.0/18 190.93.240.0/20 188.114.96.0/20 197.234.240.0/22 198.41.128.0/17 162.158.0.0/15 104.16.0.0/13 104.24.0.0/14 172.64.0.0/13 131.0.72.0/22 2400:cb00::/32 2606:4700::/32 2803:f800::/32 2405:b500::/32 2405:8100::/32 2a06:98c0::/29 2c0f:f248::/32"
CF_LIVE="$(curl -fsS --max-time 10 https://www.cloudflare.com/ips-v4 2>/dev/null; echo; curl -fsS --max-time 10 https://www.cloudflare.com/ips-v6 2>/dev/null)"
CF_LIVE="$(printf '%s\n' "$CF_LIVE" | grep -E '^[0-9a-fA-F:.]+/[0-9]+$' | tr '\n' ' ')"
[ "$(printf '%s' "$CF_LIVE" | wc -w)" -ge 10 ] && CF_RANGES="$CF_LIVE" || CF_RANGES="$CF_BUILTIN"
cf_restrict() { printf '# managed by crm-setup.sh — only Cloudflare may reach %s\n@crm_not_cloudflare not remote_ip %s\nrespond @crm_not_cloudflare "Forbidden" 403\n' "$DOMAIN" "$CF_RANGES" > "$CFI"; }
cf_open() { printf '# managed by crm-setup.sh — Cloudflare-only restriction OFF (site was not reachable through Cloudflare)\n' > "$CFI"; }
caddy_reload() { if [ "$NO_SYSTEMD" = 1 ]; then caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1 || true; else systemctl reload caddy; fi; }
[ -f "$CFI" ] && cp "$CFI" /tmp/crm-cf.previous || : > /tmp/crm-cf.previous
cf_restrict; chmod 644 "$CFI"
# Older laptop Caddyfiles: add the import line to the site block if it is missing.
if [ -n "$CADDY_NEW" ] && [ -f "$CADDY_NEW" ] && ! grep -q "crm-cloudflare-only.caddy" "$CADDY_NEW"; then
  DRE="$(printf '%s' "$DOMAIN" | sed 's/[.]/[.]/g')"
  sed -i "0,/^[[:space:]]*${DRE}[[:space:]]*{[[:space:]]*\r\{0,1\}\$/s//&\n\timport \/etc\/caddy\/crm-cloudflare-only.caddy/" "$CADDY_NEW"
  grep -q "crm-cloudflare-only.caddy" "$CADDY_NEW" && ok "Cloudflare-only rule added to the $DOMAIN block of the uploaded Caddyfile"
fi
if [ -n "$CADDY_NEW" ] && [ -f "$CADDY_NEW" ]; then
  grep -q "$DOMAIN" "$CADDY_NEW" || die "the uploaded Caddyfile has no $DOMAIN block"
  if ! cmp -s "$CADDY_NEW" /etc/caddy/Caddyfile; then
    cp -a /etc/caddy/Caddyfile "/etc/caddy/Caddyfile.bak-$(date +%Y%m%d-%H%M%S)"
    cp /etc/caddy/Caddyfile /tmp/Caddyfile.previous
    install -m 644 "$CADDY_NEW" /etc/caddy/Caddyfile
    if caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/tmp/caddy-validate.log 2>&1; then
      chown -R caddy:caddy /var/log/caddy
      if [ "$NO_SYSTEMD" = 1 ]; then caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1 || true; else systemctl reload caddy; fi
      ok "Caddyfile validated and reloaded (previous copy kept as /etc/caddy/Caddyfile.bak-*)"
    else
      cat /tmp/caddy-validate.log
      install -m 644 /tmp/Caddyfile.previous /etc/caddy/Caddyfile; chown -R caddy:caddy /var/log/caddy
      die "new Caddyfile is invalid — the previous one was restored, nothing changed"
    fi
  else
    chown -R caddy:caddy /var/log/caddy 2>/dev/null || true
    ok "Caddyfile unchanged"
  fi
else
  ok "no Caddyfile supplied — Caddy untouched"
fi
if grep -q "crm-cloudflare-only.caddy" /etc/caddy/Caddyfile; then
  if ! cmp -s "$CFI" /tmp/crm-cf.previous; then
    caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/tmp/caddy-validate.log 2>&1 || { cat /tmp/caddy-validate.log; cp /tmp/crm-cf.previous "$CFI"; die "Cloudflare list rejected by Caddy — previous one kept"; }
    chown -R caddy:caddy /var/log/caddy; caddy_reload
  fi
  sleep 2
  CODE="$(curl -s -o /dev/null -w '%{http_code}' --max-time 20 "https://$DOMAIN/api/ready" || true)"
  if [ "$CODE" = 200 ]; then
    ok "only Cloudflare can reach $DOMAIN (direct access to the server IP is refused)"
  else
    cf_open; chown -R caddy:caddy /var/log/caddy; caddy_reload
    printf '\033[1;33m  ! %s answered %s through Cloudflare — Cloudflare-only restriction switched OFF to keep the site up.\n    Check that the DNS record for %s is "Proxied" (orange cloud) in Cloudflare, then deploy again.\033[0m\n' "$DOMAIN" "$CODE" "$DOMAIN"
  fi
fi

say "8/8 Backups and admin helper"
cat > /etc/cron.d/crm-backup <<CRON
# Smart Sales CRM — daily database backup 03:15, kept 14 days ($BK)
15 3 * * * root runuser -u postgres -- pg_dump ${PSQL_ARGS[*]} -d $DB --format=custom --exclude-schema=pgboss > $BK/crm-\$(date +\%F).dump && chmod 600 $BK/crm-*.dump && find $BK -name 'crm-*.dump' -mtime +14 -delete
CRON
chmod 644 /etc/cron.d/crm-backup
cat > /usr/local/sbin/crm-admin <<'ADMIN'
#!/usr/bin/env bash
# Create (or promote) a Smart Sales CRM Super Admin:  crm-admin --email you@example.com --name "Your Name"
# The password is asked interactively and never stored anywhere but as a hash in the database.
exec runuser -u crm -- bash -c 'set -a; . /etc/crm/crm.env; set +a; cd /opt/crm && exec node scripts/create-platform-admin.js "$@"' crm-admin "$@"
ADMIN
chmod 750 /usr/local/sbin/crm-admin
ok "/etc/cron.d/crm-backup and /usr/local/sbin/crm-admin installed"

ADMINS="$(pg -d $DB -c "SET app.platform_admin = 'on'; SELECT count(*) FROM users WHERE is_platform_admin" 2>/dev/null | tail -1 || echo '?')"
printf '\n\033[1;32m=== Smart Sales CRM is running: https://%s ===\033[0m\n' "$DOMAIN"
echo "Version: $(cat "$APP/RELEASE" 2>/dev/null || echo unknown)"
[ "$ADMINS" = "0" ] && echo "No Super Admin yet — run on the server:  crm-admin --email you@example.com --name \"Your Name\""
exit 0
